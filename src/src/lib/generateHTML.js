function lightenHex(hex, pct) {
  try {
    const n = parseInt(hex.replace('#',''), 16);
    const r = Math.min(255, ((n>>16)&255) + Math.round(pct*2.55));
    const g = Math.min(255, ((n>>8)&255)  + Math.round(pct*2.55));
    const b = Math.min(255, (n&255)       + Math.round(pct*2.55));
    return `#${((1<<24)+(r<<16)+(g<<8)+b).toString(16).slice(1)}`;
  } catch { return hex; }
}

function darkenHex(hex, pct) {
  try {
    const n = parseInt(hex.replace('#',''), 16);
    const r = Math.max(0, ((n>>16)&255) - Math.round(pct*2.55));
    const g = Math.max(0, ((n>>8)&255)  - Math.round(pct*2.55));
    const b = Math.max(0, (n&255)       - Math.round(pct*2.55));
    return `#${((1<<24)+(r<<16)+(g<<8)+b).toString(16).slice(1)}`;
  } catch { return hex; }
}

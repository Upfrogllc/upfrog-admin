const WORKER_URL = 'https://upfrog-proxy.shiny-poetry-341c.workers.dev';

export function generateFunnelHTML(client, vertical) {
  const pb = vertical.pricebook;
  const ghl = client.ghl;
  const vertId = vertical.verticalId;

  // Build the CONFIG block
  const config = {
    worker:      WORKER_URL,
    webhook:     ghl.webhookUrl || '',
    calendarUrl: ghl.calendarUrl || '',
    vertical:    vertId,
    brandSlug:   client.slug,
    brandName:   client.name,
    phone:       client.phone,
    brandColor:  client.brandColor || '#c0572a',
  };

  // Pricebook varies by vertical
  const priceConfig = vertId === 'roofing' ? buildRoofingPriceConfig(pb) : buildGenericPriceConfig(pb, vertId);

  return `<!--
=======================================================
  ${client.name} — ${vertId.charAt(0).toUpperCase() + vertId.slice(1)} Estimate Funnel
  Generated by Upfrog Admin on ${new Date().toLocaleDateString()}
  Paste into GHL > Funnels > Page > Custom HTML block
=======================================================
-->
${getFunnelTemplate(config, priceConfig, vertId, client)}`;
}


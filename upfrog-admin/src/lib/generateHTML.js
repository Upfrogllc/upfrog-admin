function buildGenericPriceConfig(pb, vertId) {
  const entries = Object.entries(pb)
    .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
    .join('\n');
  return `  price: {\n${entries}\n  },`;
}

